#!/usr/bin/env node
// Generate `docs/assets/wirescript-hljs.js`, the highlight.js language mdBook
// loads for ```wirescript blocks, from the Monarch grammar the playground
// already uses (`crates/wasm/playground/monarch.js`). One keyword list feeds
// the editor and the book.
//
//   node crates/wirescript/scripts/gen_hljs_lang.mjs           # write
//   node crates/wirescript/scripts/gen_hljs_lang.mjs --check   # CI gate

import { readFileSync } from 'fs';
import { join } from 'path';
import { pathToFileURL } from 'url';
import { repoRoot, writeOrCheck } from './lib.mjs';

const outPath = join(repoRoot, 'docs', 'assets', 'wirescript-hljs.js');
const monarch = join(repoRoot, 'crates', 'wasm', 'playground', 'monarch.js');

const { monarchLanguage: g } = await import(pathToFileURL(monarch).href);

const words = (xs) => [...new Set(xs)].sort().join(' ');

const body = `// Generated by scripts/gen_hljs_lang.mjs from monarch.js. Do not edit.
(function () {
  if (typeof hljs === 'undefined') return;

  hljs.registerLanguage('wirescript', function (hljs) {
    return {
      name: 'Wirescript',
      keywords: {
        keyword: ${JSON.stringify(words(g.keywords))},
        type: ${JSON.stringify(words(g.typeKeywords))},
        built_in: ${JSON.stringify(words([...g.builtins, ...g.events]))},
        literal: ${JSON.stringify(words(g.constants || []))},
      },
      contains: [
        hljs.C_LINE_COMMENT_MODE,
        hljs.C_BLOCK_COMMENT_MODE,
        hljs.C_NUMBER_MODE,
        // Interpolation is \${...} inside an ordinary string.
        {
          className: 'string',
          begin: '"', end: '"',
          illegal: '\\\\n',
          contains: [
            { begin: '\\\\\\\\.' },
            { className: 'subst', begin: '\\\\\\${', end: '}' },
          ],
        },
        { className: 'string', begin: "'", end: "'", illegal: '\\\\n' },
        // Annotations: @layout("code"), @closed, @label(...)
        { className: 'meta', begin: '@[A-Za-z_][A-Za-z0-9_]*' },
        // Asset and prefab references: $Item/Foo, $./file.brz
        { className: 'symbol', begin: '\\\\\\$[A-Za-z0-9_./-]+' },
      ],
    };
  });

  // mdBook ships highlight.js 10.x, whose entry point is highlightBlock.
  // highlightElement is the 11.x name, tried first so a future mdBook works.
  var highlight = hljs.highlightElement || hljs.highlightBlock;
  if (!highlight) return;

  // These blocks are already highlighted by the time this runs, and with the
  // WRONG grammar: an unregistered language sends hljs 10 down its
  // auto-detection path. Flatten back to plain text first, or the stale spans
  // survive underneath the new ones.
  var blocks = document.querySelectorAll('code.language-wirescript');
  for (var i = 0; i < blocks.length; i++) {
    var el = blocks[i];
    el.textContent = el.textContent;
    el.className = el.className.replace(/\\bhljs\\b/g, '').trim();
    el.removeAttribute('data-highlighted');
    highlight.call(hljs, el);
  }

})();
`;

// The VS Code grammar's word lists, rewritten in place in its JSON text so the
// file's hand formatting stays. `unsafe` and `is` keep their own contextual
// rules; the declaration keywords take the declaration scope.
const tmPath = join(repoRoot, 'editors', 'vscode', 'syntaxes', 'wirescript.tmLanguage.json');
const CONTEXTUAL = new Set(['unsafe', 'is']);
const DECLARATIONS = new Set([
  'var', 'array', 'map', 'static', 'buffer', 'let', 'const', 'fn', 'chip', 'mod',
  'in', 'out', 'ref', 'import', 'type', 'enum',
]);
const alternation = (xs) => [...new Set(xs)].sort().join('|');
const tmLists = {
  'keyword.control.wirescript': g.keywords.filter((k) => !CONTEXTUAL.has(k) && !DECLARATIONS.has(k)),
  'keyword.declaration.wirescript': g.keywords.filter((k) => DECLARATIONS.has(k)),
  'support.type.wirescript': g.typeKeywords,
  'support.function.wirescript': g.builtins,
  'support.constant.event.wirescript': g.events,
  'constant.language.wirescript': g.constants || [],
};
const EVENTS_RULE = `        {
          "name": "support.constant.event.wirescript",
          "match": ""
        }`;

function tmText(current) {
  let text = current.replace(/\r\n/g, '\n');
  if (!text.includes('"support.constant.event.wirescript"')) {
    // The events rule sits beside the builtins one.
    const at = text.indexOf('"name": "support.function.wirescript"');
    const end = text.indexOf('\n        }', at) + '\n        }'.length;
    text = text.slice(0, end) + ',\n' + EVENTS_RULE + text.slice(end);
  }
  for (const [scope, words] of Object.entries(tmLists)) {
    const rule = new RegExp(`("name": "${scope.replace(/\./g, '\\.')}",\\s*"match": )"[^"\\n]*"`);
    if (!rule.test(text)) throw new Error(`gen_hljs_lang: no "${scope}" rule in ${tmPath}`);
    const match = JSON.stringify(`\\b(${alternation(words)})\\b`);
    text = text.replace(rule, (_, head) => head + match);
  }
  return current.includes('\r\n') ? text.replace(/\n/g, '\r\n') : text;
}

const readOr = (path) => {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
};
const tmCurrent = readOr(tmPath);
const tmBody = tmText(tmCurrent);

const check = process.argv.includes('--check');
const fresh = [
  writeOrCheck(outPath, body, { check, what: 'gen_hljs_lang: docs/assets/wirescript-hljs.js', fix: 'just doc-hljs' }),
  writeOrCheck(tmPath, tmBody, { check, what: 'gen_hljs_lang: editors/vscode/syntaxes/wirescript.tmLanguage.json', fix: 'just doc-hljs' }),
];
if (fresh.includes(false)) process.exit(1);
if (check) {
  console.log('gen_hljs_lang: wirescript-hljs.js and the VS Code grammar are up to date');
} else {
  console.log(
    `gen_hljs_lang: wrote docs/assets/wirescript-hljs.js and the VS Code grammar ` +
      `(${g.keywords.length} keywords, ${g.typeKeywords.length} types, ` +
      `${g.builtins.length + g.events.length} builtins)`,
  );
}
