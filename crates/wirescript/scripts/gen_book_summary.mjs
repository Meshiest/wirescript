#!/usr/bin/env node
// Generate `docs/src/SUMMARY.md`, mdBook's table of contents, from the page
// list in `crates/wasm/playground/docs.js`. That list is the single source for
// the playground panel, its search index, and the book, so a page registered
// once appears in all three.
//
//   node crates/wirescript/scripts/gen_book_summary.mjs           # write
//   node crates/wirescript/scripts/gen_book_summary.mjs --check   # CI gate
//
// Both modes fail on a `.md` in `docs/src/` that is registered nowhere;
// `--check` also fails when SUMMARY.md on disk is stale.

import { join } from 'path';
import { pathToFileURL } from 'url';
import { filesUnder, repoRoot, writeOrCheck } from './lib.mjs';

const docsDir = join(repoRoot, 'docs', 'src');
const summaryPath = join(docsDir, 'SUMMARY.md');
const docsJs = join(repoRoot, 'crates', 'wasm', 'playground', 'docs.js');

const { DOCS } = await import(pathToFileURL(docsJs).href);

// Page paths are site-relative (`docs/syntax.md`); the book's are relative to
// `docs/src`.
const fileOf = (d) => (d.file ? d.file.slice('docs/'.length) : null);

const lines = ['<!-- Generated by scripts/gen_book_summary.mjs. Do not edit. -->', ''];
const covered = new Set();
for (const d of DOCS) {
  const file = fileOf(d);
  // `Playground` is the panel's own inline help, with no file to link.
  if (!file) continue;
  covered.add(file);
  // A prefix chapter (no bullet) is what mdBook renders at `/docs/` itself.
  if (file === 'README.md' && lines.length === 2) {
    lines.push(`[${d.title}](README.md)`, '');
    continue;
  }
  lines.push(`- [${d.title}](${file})`);
  // A page's children nest under it, grouped under their `branch` when they
  // have one; a branch name is a chapter with no page of its own.
  let branch = null;
  for (const c of d.children || []) {
    const childFile = fileOf(c);
    covered.add(childFile);
    if (c.branch && c.branch !== branch) {
      branch = c.branch;
      lines.push(`  - [${branch}]()`);
    }
    lines.push(`${c.branch ? '    ' : '  '}- [${c.title}](${childFile})`);
  }
}
lines.push('');

// CHANGELOG.md is staged in by the build, not tracked here.
const onDisk = filesUnder(docsDir, '.md').filter((f) => f !== 'SUMMARY.md' && f !== 'CHANGELOG.md');
const unregistered = onDisk.filter((f) => !covered.has(f));
if (unregistered.length) {
  console.error(
    `gen_book_summary: ${unregistered.join(', ')} in docs/src/ is not registered in ` +
      `crates/wasm/playground/docs.js. Add it to DOCS ` +
      `so it appears in both the playground panel and the book.`,
  );
  process.exit(1);
}

const next = lines.join('\n');
const check = process.argv.includes('--check');
if (!writeOrCheck(summaryPath, next, { check, what: 'gen_book_summary: docs/src/SUMMARY.md', fix: 'just doc-summary' })) {
  process.exit(1);
}
console.log(
  check
    ? `gen_book_summary: SUMMARY.md up to date (${covered.size} pages)`
    : `gen_book_summary: wrote docs/src/SUMMARY.md (${covered.size} pages)`,
);
